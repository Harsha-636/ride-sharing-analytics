# ------------------------------------------------------------------
# Groq chat helper — used by the "Ask the Data" tab. Free API key
# from console.groq.com, stored as GROQ_API_KEY in Streamlit secrets.
# ------------------------------------------------------------------
GROQ_MODEL = "openai/gpt-oss-120b"  # current Groq-recommended general model; change here if retired


def call_groq(messages, temperature=0.3):
    api_key = st.secrets.get("GROQ_API_KEY")
    if not api_key:
        return None, (
            "No GROQ_API_KEY found in Streamlit secrets. Get a free key at "
            "console.groq.com, then add it under Settings → Secrets in the "
            "Streamlit Cloud dashboard as:\n\nGROQ_API_KEY = \"your-key-here\""
        )
    try:
        resp = requests.post(
            "https://api.groq.com/openai/v1/chat/completions",
            headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
            json={"model": GROQ_MODEL, "messages": messages, "temperature": temperature},
            timeout=30,
        )
        resp.raise_for_status()
        return resp.json()["choices"][0]["message"]["content"], None
    except requests.exceptions.HTTPError as e:
        return None, f"Groq API error ({resp.status_code}): {resp.text[:300]}"
    except Exception as e:
        return None, f"Request to Groq failed: {e}"

# ------------------------------------------------------------------
# 1. Default seed data — loaded from the bundled CSVs (500 trips /
#    40 riders / 18 drivers, generated by generate_data.py). Falls
#    back to a small inline sample if the CSVs aren't present, so the
#    app still runs even if only app.py gets copied somewhere.
# ------------------------------------------------------------------
APP_DIR = os.path.dirname(os.path.abspath(__file__))


def _load_default(csv_name, fallback_rows, columns):
    path = os.path.join(APP_DIR, csv_name)
    if os.path.exists(path):
        return pd.read_csv(path)
    return pd.DataFrame(fallback_rows, columns=columns)


