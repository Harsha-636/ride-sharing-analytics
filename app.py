def build_connection(riders_df, drivers_df, trips_df):
    """Rebuild a fresh in-memory SQLite DB from the current edited data."""
    conn = sqlite3.connect(":memory:", check_same_thread=False)
    riders_df.to_sql("riders", conn, index=False, if_exists="replace")
    drivers_df.to_sql("drivers", conn, index=False, if_exists="replace")
    trips_df.to_sql("trips", conn, index=False, if_exists="replace")
    return conn


def q(conn, sql, params=None):
    return pd.read_sql_query(sql, conn, params=params)


# ------------------------------------------------------------------
# 3. Page skeleton — title/caption first, then a placeholder for the
#    KPI row (filled in AFTER we've read this run's edits, further
#    down), then the tabs. Using a placeholder lets the KPI row stay
#    visually at the top while still reflecting the latest edits.
# ------------------------------------------------------------------
st.title("🚖 Ride-Sharing Analytics Dashboard")
st.caption("Edit data in the ✏️ Edit Data tab — every chart and KPI updates live as you type.")
