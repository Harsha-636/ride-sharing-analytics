"""
Ride-Sharing Analytics Dashboard
---------------------------------
Single-file Streamlit app. Data lives in an editable spreadsheet-style
grid (the "Edit Data" tab) — no code editing needed to change names,
fares, cities, etc. Every chart and KPI recalculates live as soon as
you edit a cell — no "Apply" button required.
"""

